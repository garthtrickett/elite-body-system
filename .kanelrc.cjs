const { makeKyselyHook } = require("kanel-kysely");

if (!process.env.DATABASE_URL) throw new Error("DATABASE_URL is required");

/** @type {import('kanel').Config} */
module.exports = {
  connection: { connectionString: process.env.DATABASE_URL },
  schemas: ["public"],
  typeFilter: type => !["function", "procedure"].includes(type.kind) &&
    !["kysely_migration", "kysely_migration_lock"].includes(type.name.toLowerCase()),
  outputPath: "./src/platform/database/generated",
  preDeleteOutputFolder: true,
  tsModuleFormat: "esm",
  preRenderHooks: [makeKyselyHook()],
  postRenderHooks: [
    (path, lines) => ["// @generated by Kanel. Run npm run db:generate; do not edit.", "",
      ...(path.endsWith("Database.ts")
        ? lines.map(line => line === "export default Database;" ? "export type { Database as default };" : line)
        : lines)],
  ],
};
